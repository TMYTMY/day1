"""Write THIRD-PARTY-NOTICES.md from the installed direct dependencies.

Reads requirements.txt and importlib.metadata only. No extra packages.
"""

from __future__ import annotations

import importlib.metadata
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REQUIREMENTS = ROOT / "requirements.txt"
OUTPUT = ROOT / "THIRD-PARTY-NOTICES.md"

_NAME = re.compile(r"^[A-Za-z0-9_.-]+")
_COPYRIGHT = re.compile(r"(?i)^copyright\s*(\(c\)|©|\d{4})")


def direct_names(path: Path) -> list[str]:
    names: list[str] = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line or line.startswith("-"):
            continue
        match = _NAME.match(line)
        if match:
            names.append(match.group(0))
    return names


def _license_name(dist: importlib.metadata.Distribution) -> str:
    meta = dist.metadata
    expression = (meta.get("License-Expression") or "").strip()
    if expression:
        return expression
    short = ""
    license_field = (meta.get("License") or "").strip()
    if license_field:
        short = license_field.splitlines()[0].strip()
    if short and len(short) <= 80 and "copyright" not in short.lower():
        return short
    classifiers = [
        item.split("::")[-1].strip()
        for item in (meta.get_all("Classifier") or [])
        if item.startswith("License ::")
    ]
    if classifiers:
        return classifiers[-1]
    return short or "Unknown"


def _is_apache(name: str) -> bool:
    compact = name.lower().replace(" ", "")
    return "apache-2.0" in compact or "apache2.0" in compact or "apachesoftwarelicense" in compact


def _texts(dist: importlib.metadata.Distribution) -> list[tuple[str, str]]:
    found: list[tuple[str, str]] = []
    seen: set[str] = set()

    def add(label: str, text: str | None) -> None:
        if not text or text in seen:
            return
        seen.add(text)
        found.append((label, text))

    license_field = (dist.metadata.get("License") or "").strip()
    if len(license_field) > 80 or "copyright" in license_field.lower():
        add("METADATA:License", license_field)
    names: list[str] = []
    for item in dist.metadata.get_all("License-File") or []:
        names.append(item)
    for rel in dist.files or []:
        upper = rel.name.upper()
        if any(token in upper for token in ("LICENSE", "NOTICE", "COPYING", "COPYRIGHT")):
            names.append(str(rel))
    for name in names:
        text = None
        try:
            text = dist.read_text(name)
        except (FileNotFoundError, OSError, UnicodeError, ValueError):
            text = None
        if not text:
            try:
                path = dist.locate_file(name)
            except (FileNotFoundError, OSError, ValueError):
                path = None
            if path is not None and path.is_file():
                text = path.read_text(encoding="utf-8", errors="replace")
        add(name, text)
    return found


_BODY = re.compile(
    r"(?i)^(redistribution|permission is hereby granted|licensed under the apache|gnu general public license)\b"
)


def _copyright_lines(texts: list[tuple[str, str]]) -> list[str]:
    """Copyright headers that sit above the license body, not the body itself."""
    lines: list[str] = []
    for _label, text in texts:
        for raw in text.splitlines():
            line = raw.strip().lstrip("*- \t>#")
            if not line:
                continue
            if _BODY.match(line):
                break
            if line in lines or "<" in line or ">" in line:
                continue
            if _COPYRIGHT.match(line):
                lines.append(line)
    return lines


def _notice_blocks(texts: list[tuple[str, str]]) -> list[str]:
    blocks: list[str] = []
    for label, text in texts:
        if Path(label).name.upper() == "NOTICE" and text.strip() and text not in blocks:
            blocks.append(text.strip())
    return blocks


def render() -> str:
    parts = [
        "# Third-party notices",
        "",
        "Generated by `scripts/gen_notices.py` from the packages installed in this environment.",
        "The list is the direct dependencies in `requirements.txt`.",
        "",
    ]
    for name in direct_names(REQUIREMENTS):
        dist = importlib.metadata.distribution(name)
        meta = dist.metadata
        texts = _texts(dist)
        copyrights = _copyright_lines(texts)
        license_name = _license_name(dist)
        parts.append(f"## {meta['Name']} {meta['Version']}")
        parts.append("")
        parts.append(f"- License: {license_name}")
        if copyrights:
            for line in copyrights:
                parts.append(f"- Copyright: {line}")
        else:
            parts.append("- Copyright: No copyright line in the installed metadata.")
        parts.append("")
        if _is_apache(license_name):
            notices = _notice_blocks(texts)
            if notices:
                for notice in notices:
                    parts.append("NOTICE:")
                    parts.append("")
                    parts.append("```")
                    parts.append(notice)
                    parts.append("```")
                    parts.append("")
            else:
                parts.append("No NOTICE file in the installed distribution.")
                parts.append("")
    return "\n".join(parts).rstrip() + "\n"


def main() -> None:
    OUTPUT.write_text(render(), encoding="utf-8")
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
